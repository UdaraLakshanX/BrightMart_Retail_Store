    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        String id = txtSupplierId.getText().trim();
        if (id.isEmpty()) {
            int viewRow = tblSuppliers.getSelectedRow();
            if (viewRow != -1) {
                int row = tblSuppliers.convertRowIndexToModel(viewRow);
                id = tblSuppliers.getModel().getValueAt(row, 0).toString();
            }
        }
        if (id.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please select a supplier to delete.", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(this, "Are you sure you want to delete supplier: " + id + "?", "Confirm Delete", JOptionPane.YES_NO_OPTION);
        if (confirm == JOptionPane.YES_OPTION) {
            try {
                Connection con = DBConnection.getConnection();
                if (con == null) {
                    JOptionPane.showMessageDialog(this, "Cannot connect to the database.", "Database Error", JOptionPane.ERROR_MESSAGE);
                    return;
                }
                String deleteSql = "DELETE FROM supplier WHERE supplier_code = ?";
                try (PreparedStatement pst = con.prepareStatement(deleteSql)) {
                    pst.setString(1, id);
                    int rows = pst.executeUpdate();
                    if (rows > 0) {
                        JOptionPane.showMessageDialog(this, "Supplier deleted successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
                        loadSuppliersData();
                        btnClearActionPerformed(evt);
                    } else {
                        JOptionPane.showMessageDialog(this, "Supplier not found: " + id, "Not Found", JOptionPane.WARNING_MESSAGE);
                    }
                }
            } catch (SQLException e) {
                if (e.getErrorCode() == 1451 || (e.getMessage() != null && e.getMessage().toLowerCase().contains("foreign key"))) {
                    JOptionPane.showMessageDialog(this,
                        "Cannot delete supplier '" + id + "' because it is linked to existing Stock Inward (GRN) records.\n" +
                        "To delete this supplier, remove the associated GRN records first.",
                        "Referential Integrity Constraint", JOptionPane.WARNING_MESSAGE);
                } else {
                    JOptionPane.showMessageDialog(this, "Database Error: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
                }
            }
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

