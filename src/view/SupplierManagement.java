    public void loadSuppliersData() {
        DefaultTableModel model = (DefaultTableModel) tblSuppliers.getModel();
        model.setRowCount(0);
        try {
            Connection con = DBConnection.getConnection();
            if (con == null) return;
            String sql = "SELECT supplier_code, name, address, contact_details FROM supplier ORDER BY supplier_code ASC";
            try (PreparedStatement pst = con.prepareStatement(sql);
                 ResultSet rs = pst.executeQuery()) {
                while (rs.next()) {
                    model.addRow(new Object[]{
                        rs.getString("supplier_code"),
                        rs.getString("name"),
                        rs.getString("contact_details") != null ? rs.getString("contact_details") : "",
                        rs.getString("address") != null ? rs.getString("address") : ""
                    });
                }
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error loading suppliers: " + e.getMessage(), "DB Error", JOptionPane.ERROR_MESSAGE);
        }
    }

