    private void tblSuppliersMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblSuppliersMouseClicked
        int viewRow = tblSuppliers.getSelectedRow();
        if (viewRow != -1) {
            int row = tblSuppliers.convertRowIndexToModel(viewRow);
            DefaultTableModel model = (DefaultTableModel) tblSuppliers.getModel();
            String id = model.getValueAt(row, 0).toString();
            try {
                Connection con = DBConnection.getConnection();
                String sql = "SELECT * FROM supplier WHERE supplier_code = ?";
                try (PreparedStatement pst = con.prepareStatement(sql)) {
                    pst.setString(1, id);
                    try (ResultSet rs = pst.executeQuery()) {
                        if (rs.next()) {
                            txtSupplierId.setText(rs.getString("supplier_code"));
                            txtSupplierName.setText(rs.getString("name"));
                            txtContactNo.setText(rs.getString("contact_details") != null ? rs.getString("contact_details") : "");
                            txtAddress.setText(rs.getString("address") != null ? rs.getString("address") : "");
                        }
                    }
                }
            } catch (SQLException e) {
                System.err.println("Error fetching supplier: " + e.getMessage());
            }
        }
    }//GEN-LAST:event_tblSuppliersMouseClicked

